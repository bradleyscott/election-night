import {
  computeObservedSwing,
  computeSeatChance,
  cycleConstantsFor,
  DEFAULT_TAU,
  type SeatChance,
  type SeatPrior,
} from '@election-night/core/seat-probability';
import { normalizeElectorateName } from '@election-night/core/electorate-names';
import type {
  ElectorateResults,
  WithLeaders,
  WithMarginOfError,
  VotingResults,
} from '@election-night/core/types';
import baseline2023 from '../data/notional-baseline-2023.json';
import baseline2026 from '../data/notional-baseline-2026.json';

type BaselineSeat = {
  kind: 'general' | 'maori';
  votes: number;
  places: number;
  partyShare: Record<string, number>;
  candidateShare: Record<string, number>;
  partyCandidateShare?: Record<string, number>;
  /**
   * Enrolled electors, recovered from the source cycle's seat file
   * (`total_votes_cast ÷ percent_votes_cast`). `null` when the seat was carried
   * over from a same-named seat rather than computed from place geometry.
   */
  enrolment?: number | null;
};

type Baseline = {
  sourceYear: number;
  targetYear: number;
  method: string;
  tau: {
    transition: string;
    seats: number;
    meanMaxAbsDeviation: number;
    sdMaxAbsDeviation: number;
    maxAbsDeviation: number;
    /**
     * sd of the leading parties' margin swing away from the national swing,
     * in vote-share points. This is the number the model uses.
     */
    sdSwingDeviation?: number;
  } | null;
  coverage: {
    seats: number;
    placesLocated: number;
    placesSkipped: number;
    inSeatResults: number;
    outOfSeatResultsDropped?: number;
  };
  seats: Record<string, BaselineSeat>;
};

/**
 * Prior results rebuilt on each cycle's boundaries, keyed by the cycle they
 * describe. Generated by `scripts/build-notional-baseline.mjs`; see
 * `docs/voting-place-data.md` for the method and its deliberate limit.
 */
const BASELINES: Record<string, Baseline> = {
  '2023': baseline2023 as unknown as Baseline,
  '2026': baseline2026 as unknown as Baseline,
};

export type ElectorateResult = ElectorateResults &
  WithLeaders &
  WithMarginOfError;

/** The cycle whose boundaries these results are drawn on. */
export const BASELINE_YEARS = Object.keys(BASELINES);

/**
 * The seat's prior result on the current boundaries, or null when the cycle
 * has no baseline (an archived year, or a run without `ELECTION_YEAR`).
 *
 * Matching is the same normalisation the boundary map uses, because the
 * baseline's keys are Stats NZ names and the feed's are the Commission's.
 */
export function priorForSeat(
  seatName: string | null | undefined,
  electionYear: string | null | undefined
): SeatPrior | null {
  if (!seatName || !electionYear) return null;
  const baseline = BASELINES[String(electionYear)];
  if (!baseline) return null;
  const wanted = normalizeElectorateName(seatName);
  for (const [name, seat] of Object.entries(baseline.seats)) {
    if (normalizeElectorateName(name) !== wanted) continue;
    return {
      partyShare: seat.partyShare,
      candidateShare: seat.candidateShare,
      partyCandidateShare: seat.partyCandidateShare,
    };
  }
  return null;
}

/**
 * How far seats typically stray from uniform national swing, as a standard
 * deviation of vote share. Measured from the archives by the baseline script;
 * the fallback is only used when no measurement was available.
 */
export function tauFor(electionYear: string | null | undefined): number {
  const baseline = BASELINES[String(electionYear ?? '')];
  const measured =
    baseline?.tau?.sdSwingDeviation ?? baseline?.tau?.sdMaxAbsDeviation;
  return measured ? measured / 100 : DEFAULT_TAU;
}

/**
 * National swing measured across the seats counted so far, for the cycle being
 * served and its baseline.
 *
 * Measured from the night's own seats rather than a published table: it needs
 * no prior national result, and it corrects itself as the advance-heavy early
 * seats stop being the whole sample.
 */
export function nationalSwingOf(
  electorates: ElectorateResult[],
  electionYear: string | null | undefined
): Record<string, number> {
  if (!electionYear) return {};
  return computeObservedSwing(
    electorates.map((result) => ({
      prior: priorForSeat(result.electorateName, electionYear),
      // The seat is decided on the candidate vote, and the prior it is
      // compared against is the party's share of that vote — so the swing has
      // to be measured there too. Measuring it on the party vote would compare
      // two different contests.
      parties: candidateVotesByParty(result.candidateVotes),
      votesCounted: result.votesCounted,
    }))
  );
}

/** Candidate votes folded up to the party that stood them. */
function candidateVotesByParty(
  votes: { candidate: string; party?: string; votes: number }[]
): VotingResults[] {
  const byParty = new Map<string, number>();
  for (const vote of votes) {
    if (!vote.party) continue;
    byParty.set(vote.party, (byParty.get(vote.party) ?? 0) + vote.votes);
  }
  return [...byParty].map(([candidate, count]) => ({
    candidate,
    votes: count,
  })) as VotingResults[];
}

/** The seat's enrolled electors in the baseline cycle, when it is recorded. */
export function enrolmentForSeat(
  seatName: string | null | undefined,
  electionYear: string | null | undefined
): number | null {
  if (!seatName || !electionYear) return null;
  const baseline = BASELINES[String(electionYear)];
  if (!baseline) return null;
  const wanted = normalizeElectorateName(seatName);
  for (const [name, seat] of Object.entries(baseline.seats)) {
    if (normalizeElectorateName(name) !== wanted) continue;
    return seat.enrolment && seat.enrolment > 0 ? seat.enrolment : null;
  }
  return null;
}

/** The chance of winning the seat, given everything already computed. */
export function seatChanceFor(
  result: ElectorateResult,
  electionYear: string | null | undefined,
  nationalSwing: Record<string, number>
): SeatChance {
  return computeSeatChance({
    candidates: result.candidateVotes.map((c) => ({
      name: c.candidate,
      party: c.party,
      votes: c.votes,
    })),
    votesCounted: result.votesCounted,
    percentVotesCast: result.percentVotesCast,
    enrolment:
      enrolmentForSeat(result.electorateName, electionYear) ?? undefined,
    electionYear: electionYear ? Number(electionYear) : null,
    prior: priorForSeat(result.electorateName, electionYear),
    nationalSwing,
    tau: tauFor(electionYear),
  });
}

/** "4 min ago", "just now", "2 hours ago". */
/**
 * How far through tonight's count a set of seats is.
 *
 * `votePercentageCounted` is the share of *voting places* that have reported,
 * and places do not carry equal numbers of votes: advance votes are counted
 * from 9am and released in large blocks after 7pm. Dividing votes by that share
 * therefore understates the count badly in the first hours. This instead
 * divides by the votes those seats are expected to receive tonight, using the
 * same enrolment-and-turnout arithmetic as the seat card, so the number on the
 * page and the number under a seat cannot disagree.
 */
export function countProgress(
  results: Array<{
    electorateName: string;
    votesCounted: number;
    percentVotesCast?: number;
  }>,
  electionYear: string | number | null
): { votesCounted: number; expected: number; fraction: number | null } {
  const cycle = cycleConstantsFor(electionYear ? Number(electionYear) : null);
  let votesCounted = 0;
  let expected = 0;
  for (const result of results) {
    if (!(result.votesCounted > 0)) continue;
    const recorded = enrolmentForSeat(
      result.electorateName,
      electionYear == null ? null : String(electionYear)
    );
    const turnout =
      result.percentVotesCast && result.percentVotesCast > 0
        ? result.percentVotesCast
        : null;
    const enrolment = recorded ?? (turnout ? result.votesCounted / turnout : null);
    if (!enrolment) continue;
    votesCounted += result.votesCounted;
    expected += enrolment * cycle.turnout * cycle.nightShare;
  }
  return {
    votesCounted,
    expected,
    fraction: expected > 0 ? votesCounted / expected : null,
  };
}

/**
 * How solidly a seat is painted on the map.
 *
 * The map answers one question — how decided is this seat — so the shading runs
 * on the chance of winning, not on the margin: a 50/50 seat is left pale
 * whichever party happens to be a hundred votes ahead, and colour deepens as
 * one side's chance grows. A seat with no votes counted gets the palest fill
 * and no claim; a finished count gets the fullest.
 */
export function mapFillOpacity(chance: SeatChance | null | undefined): number {
  if (!chance || chance.state === 'waiting') return 0.15;
  if (chance.state === 'complete') return 0.8;
  // 0.5 → 0.2, 0.99 → 0.8. A seat at even odds is nearly invisible on purpose:
  // painting it solid in the leader's colour is the mistake this replaces.
  return 0.2 + Math.min(1, Math.abs(chance.probability - 0.5) / 0.49) * 0.6;
}

export function formatUpdatedAgo(
  updatedAt: Date | null,
  now = new Date()
): string | null {
  if (!updatedAt) return null;
  const seconds = Math.max(
    0,
    Math.round((now.getTime() - updatedAt.getTime()) / 1000)
  );
  if (seconds < 45) return 'just now';
  const minutes = Math.round(seconds / 60);
  if (minutes < 60) return `${minutes} min ago`;
  const hours = Math.round(minutes / 60);
  return `${hours} ${hours === 1 ? 'hour' : 'hours'} ago`;
}
